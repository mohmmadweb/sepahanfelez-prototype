def price_block(key, row, rows, ctx):
    """HTML بخش تحلیل قیمت این کد.

    ctx باید price_of / slugify / esc / fa / phone را بدهد.
    همه‌ی اعداد از داده‌ی خود ردیف می‌آیند، پس متن هر صفحه یکتاست.
    """
    price_of, slug = ctx["price_of"], ctx["slugify"]
    esc, fa, PHS = ctx["esc"], ctx["fa"], ctx["phone"]

    p = price_of(row)
    e = economics(key, row, p)
    if not p or not (e["per_m2"] or e["per_kg"] or e["piece"]):
        return ""

    eco = [economics(key, r, price_of(r)) for r in rows]

    # ---- مبنای اصلیِ مقایسه ----
    if e["per_m2"]:
        basis_key, this_val = "per_m2", e["per_m2"]
        vals = [x["per_m2"] for x in eco]
        basis_label, basis_unit = "هر متر مربع", "متر مربع"
    elif e["piece"]:
        basis_key, this_val = "piece", e["piece"][1]
        vals = [x["piece"][1] if x["piece"] else None for x in eco]
        basis_label, basis_unit = f"هر {e['piece'][0]}", e["piece"][0]
    else:
        basis_key, this_val = "per_kg", e["per_kg"]
        vals = [x["per_kg"] for x in eco]
        basis_label, basis_unit = "هر کیلوگرم", "کیلوگرم"

    # ---- کارت‌های عدد ----
    cards = []
    if e["piece"]:
        cards.append((f"قیمت هر {e['piece'][0]}", money_fa(e["piece"][1]),
                      f"ریال / {e['piece'][0]}"))
    if e["per_m2"]:
        cards.append(("قیمت هر متر مربع", money_fa(e["per_m2"]), "ریال / m²"))
    if e["per_kg"]:
        cards.append(("قیمت هر کیلوگرم", money_fa(e["per_kg"]), "ریال / kg"))
    if e["per_ton"] and len(cards) < 4:
        cards.append(("قیمت هر تن", money_fa(e["per_ton"]), "ریال / تن"))
    cards = cards[:4]

    grid = "".join(
        f'<div class="ix"><span class="k">{esc(k)}</span>'
        f'<span class="v"><span class="num">{v}</span></span>'
        f'<span class="range">{esc(u)}</span></div>' for k, v, u in cards)

    # ---- رتبه، فقط اگر داده سالم باشد ----
    bad = outliers(vals)
    me = next((i for i, r in enumerate(rows)
               if r["نام محصول"] == row["نام محصول"]), None)
    body = []

    # اگر واحدِ فروشِ ردیف‌های یک دسته یکسان نباشد، «ارزان‌ترین» معنی ندارد:
    # در سیم خاردار، کلافِ خطی ۲۰ کیلوگرم است و کلافِ سوزنی ۷ کیلوگرم. کنار
    # هم گذاشتنشان دو کمیت متفاوت را با یک برچسب مقایسه می‌کند و ادعای
    # «مقرون‌به‌صرفه‌ترین» را نادرست از آب درمی‌آورد.
    same_basis = len({(r.get("واحد") or "").strip() for r in rows}) == 1

    if same_basis and me is not None and me not in bad:
        good = [(i, v) for i, v in enumerate(vals) if v and i not in bad]
        if len(good) >= 3:
            ordered = sorted(good, key=lambda t: t[1])
            pos = next(n for n, (i, _) in enumerate(ordered, 1) if i == me)
            n = len(ordered)
            if pos == 1:
                body.append(
                    f"<p>روی مبنای <b>{esc(basis_label)}</b>، این کد "
                    f"<b>مقرون‌به‌صرفه‌ترین</b> گزینه‌ی این دسته در میان "
                    f"{fa(n)} کد سنجیده‌شده است.</p>")
            else:
                ci, cv = ordered[0]
                gap = (this_val - cv) / cv * 100 if cv else 0
                cheap = rows[ci]["نام محصول"]
                body.append(
                    f"<p>روی مبنای <b>{esc(basis_label)}</b>، این کد در جایگاه "
                    f"<b>{fa(pos)}م از {fa(n)}</b> کد این دسته قرار دارد.</p>")
                if gap >= 5:
                    body.append(
                        f'<div class="callout"><div class="t">'
                        f'چنانچه مشخصات فنی قابل تغییر باشد</div>'
                        f'<p>کم‌هزینه‌ترین کد این دسته روی همین مبنا '
                        f'<a href="p-{slug(cheap)}.html">{esc(cheap)}</a> است با '
                        f'<span class="num">{money_fa(cv)}</span> ریال برای هر '
                        f'{esc(basis_unit)} — یعنی <b>{fa(round(gap))}٪</b> کمتر. '
                        f'چنانچه ضخامت مفتول و چشمه‌ی آن با کاربرد شما تناسب دارد، '
                        f'صرفه‌جویی حاصل را در تناژ سفارش لحاظ بفرمایید.</p></div>')
    elif me in bad:
        body.append(
            '<p class="tnote">عدد این ردیف با بقیه‌ی کدهای دسته هم‌خوان نیست و '
            'در حال بازبینی است. پیش از سفارش، قیمت را تلفنی بگیرید.</p>')

    # ---- مثال کمّی ----
    if e["per_m2"]:
        body.append(
            f"<p>برآورد اولیه: پوشش <b>۱۰۰ متر مربع</b> با این کد حدود "
            f"<span class=\"num\">{money_fa(e['per_m2'] * 100)}</span> ریال "
            f"خواهد بود؛ پیش از احتساب هزینه‌ی حمل و ارزش افزوده.</p>")
    elif e["per_kg"] and e["piece"]:
        each = e["piece"][1] / e["per_kg"]
        if each:
            body.append(
                f"<p>هر تن از این کد تقریباً <b>{fa(round(1000 / each))} "
                f"{esc(e['piece'][0])}</b> می‌شود.</p>")

    body.append(
        f'<p>این اعداد از وزن و ابعاد ثبت‌شده‌ی همین کد حساب شده‌اند و '
        f'مبنای روزند. برای <b>قیمت قطعی</b> تناژ و مقصد بار لازم است — '
        f'<span class="num">{PHS}</span>.</p>')

    lede = _BASIS_NOTE.get(e["basis"],
                           "قیمت جدول مبنای روز است. آنچه قابل‌مقایسه است")

    # بدون <section>: این خروجی داخل .container صفحه‌ی محصول می‌نشیند،
    # وگرنه پدینگ ظرف دو بار اعمال می‌شود.
    return f"""
      <div class="prose">
        <h2>قیمت قابل‌مقایسه‌ی این کد</h2>
        <p>{lede} چیز دیگری است. این بخش همان تبدیل را انجام می‌دهد تا
           امکان مقایسه‌ی این کد با هر پیشنهاد دیگری فراهم باشد.</p>
      </div>
      <div class="ixgrid ix-{len(cards)} ix-tight">{grid}</div>
      <div class="prose">{''.join(body)}</div>"""


