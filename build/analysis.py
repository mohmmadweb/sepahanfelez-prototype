def geometry(key, row):
    """مساحت و وزن هر «قطعه»ی فروش، و وزن هر متر مربع.

    خروجی: (نام قطعه، مساحت هر قطعه m²، وزن هر قطعه kg، وزن هر m² kg)
    هرکدام که از داده درنیامد None می‌ماند.
    """
    g = lambda k: row.get(k)
    piece, area, weight, w_m2 = None, None, None, None

    if key == "توری-جوشی--گالوانیزه-رول":
        piece, area, weight = "رول", num(g("متراژ رول (متر مربع)")), num(g("وزن هر رول (تقریبی)"))

    elif key == "توری-حصاری":
        piece, w_m2 = "رول", num(g("وزن هر متر مربع (کیلوگرم)"))
        L, W = num(g("طول رول (متر)")), num(g("عرض (سانتی متر)"))
        if L and W:                      # عرض اغلب «سفارشی» است → مساحت رول درنمی‌آید
            area = L * W / 100.0

    elif key in ("توری-فرنگی", "توری-مرغی"):
        piece, weight = "رول", num(g("وزن (کیلوگرم)"))
        L, W = num(g("طول (متر)")), num(g("عرض (سانتی متر)"))
        if L and W:
            area = L * W / 100.0

    elif key == "توری-پرسی":
        piece, weight = "برگ", num(g("وزن هر برگ"))

    elif key == "توری-گابیون":
        piece = "پانل"
        w_g = num(g("وزن هر متر مربع (گرم)"))
        w_m2 = w_g / 1000.0 if w_g else None
        L, W = num(g("طول (متر)")), num(g("عرض (سانتی متر)"))
        if L and W:
            area = L * W / 100.0

    elif key == "سیم-خاردار":
        piece, weight = "کلاف", num(g("وزن (کیلوگرم)"))

    elif key == "مش-جوشی-یا-مش-آهنی":
        piece, weight = "برگ", num(g("وزن هر برگ"))
        d = dims(g("طول*عرض (متر)"))
        if d:
            area = d[0] * d[1]

    elif key == "سیم-سیاه-و-آرماتور-بندی":
        piece, weight = "کلاف", num(g("وزن (کیلوگرم)"))   # اغلب «فله بار» → None

    # وزن هر قطعه و وزن هر متر مربع هرکدام می‌توانند آن یکی را بسازند
    if weight is None and area and w_m2:
        weight = area * w_m2
    if w_m2 is None and area and weight:
        w_m2 = weight / area
    return piece, area, weight, w_m2


