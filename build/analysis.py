def outliers(vals, factor=4.0):
    """اندیس مقادیری که نسبت به میانه‌ی دسته بیش از factor برابر پرت‌اند.

    چرا لازم است: چند ردیف کاتالوگ آشکارا غلط وارد شده‌اند — دو رول توری
    جوشی با قیمت ۱,۹۰۰,۰۰۰ ریال کنار هم‌خانواده‌هایی که ۳۴ تا ۴۹ میلیون‌اند.
    اگر همین‌طور منتشر شود، صفحه با اطمینان می‌گوید «ارزان‌ترین کد این دسته»
    و اولین خریداری که زنگ بزند می‌فهمد عدد غلط است. یک «مرجع قیمت» با
    همین یک تماس اعتبارش را از دست می‌دهد.

    پس ادعای «ارزان‌ترین/گران‌ترین» برای ردیف پرت ساخته نمی‌شود و ردیف در
    گزارش ساخت علامت می‌خورد تا صاحب سایت راستی‌آزمایی کند.
    """
    clean = sorted(v for v in vals if v)
    if len(clean) < 4:
        return set()
    mid = clean[len(clean) // 2]
    if not mid:
        return set()
    return {i for i, v in enumerate(vals)
            if v and (v > mid * factor or v * factor < mid)}


def money_fa(n):
    """عدد ریال، گرد‌شده به سطحی که خواندنش برای انسان معنی دارد."""
    n = float(n)
    if n >= 10_000_000:
        n = round(n / 100_000) * 100_000
    elif n >= 1_000_000:
        n = round(n / 10_000) * 10_000
    elif n >= 100_000:
        n = round(n / 1_000) * 1_000
    else:
        n = round(n / 100) * 100
    return f"{int(n):,}"


