# تجزیه‌ی عدد
# ---------------------------------------------------------------------------
def num(v):
    """'22 کیلوگرم' → 22.0 ، '1/200' → 1.2 ، 'فله بار' → None

    در فارسی «/» جداکننده‌ی اعشار است. این تابع فقط روی فیلدهای وزن/طول/
    عرض/متراژ صدا زده می‌شود — نه روی «چشمه (اینچ)» که در آن 3/4 کسر است
    نه اعشار.
    """
    if v is None:
        return None
    s = str(v).strip()
    if not s or s == "—":
        return None
    s = s.replace("٫", "/").replace("،", "")
    m = re.search(r"\d+(?:[/.]\d+)?", s)
    if not m:
        return None
    try:
        return float(m.group(0).replace("/", "."))
    except ValueError:
        return None


def dims(v):
    """'30*1/20' → (30.0, 1.2) ، '6*2' → (6.0, 2.0)"""
    if not v:
        return None
    parts = str(v).split("*")
    if len(parts) != 2:
        return None
    a, b = num(parts[0]), num(parts[1])
    return (a, b) if a and b else None


