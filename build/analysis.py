def rank_on(metric, this_val, all_vals):
    """رتبه‌ی این کد میان هم‌دسته‌ای‌ها روی یک مبنای مشخص.

    خروجی: (رتبه، تعداد، ارزان‌ترین مقدار) — رتبه ۱ یعنی ارزان‌ترین.
    """
    vals = sorted(v for v in all_vals if v)
    if not vals or not this_val:
        return None
    # رتبه بر اساس مقدار، نه اندیس — کدهای هم‌قیمت رتبه‌ی یکسان می‌گیرند
    rank = 1 + sum(1 for v in vals if v < this_val - 0.5)
    return (rank, len(vals), vals[0])


