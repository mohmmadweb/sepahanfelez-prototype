# کلید خروجی:
#   basis      واحدی که قیمت جدول به آن است
#   per_m2     ریال به ازای هر متر مربع
#   per_kg     ریال به ازای هر کیلوگرم
#   piece      (نام قطعه، قیمت هر قطعه)   مثلا ('رول', 48500000)
#   per_ton    ریال به ازای هر تن
_PIECE_UNITS = ("رول", "کلاف", "برگ", "پانل", "شاخه", "عدد", "بسته")

def economics(key, row, price):
    """اقتصاد یک ردیف. price = قیمت جدول (ریال) به واحدِ همان ردیف.

    واحد از خود ردیف خوانده می‌شود، نه از دسته: در «سیم خاردار» ردیف خطی
    کیلوگرمی است و ردیف‌های سوزنی کلافی. اگر واحد را دسته‌ای فرض کنیم،
    قیمت هر کیلوگرم سوزنی هفت برابر واقعیت اعلام می‌شود.
    """
    unit = (row.get("واحد") or "").strip()
    out = {"basis": unit, "per_m2": None, "per_kg": None,
           "piece": None, "per_ton": None}
    if not price:
        return out

    piece, area, weight, w_m2 = geometry(key, row)

    if unit == "کیلوگرم":
        out["per_kg"] = price
        if weight and piece:
            out["piece"] = (piece, price * weight)
        if w_m2:
            out["per_m2"] = price * w_m2
    elif unit == "مترمربع":
        out["per_m2"] = price
        if w_m2:
            out["per_kg"] = price / w_m2
        if area and piece:
            out["piece"] = (piece, price * area)
    elif unit in _PIECE_UNITS:
        out["piece"] = (unit, price)
        if area:
            out["per_m2"] = price / area
        if weight:
            out["per_kg"] = price / weight

    if out["per_kg"]:
        out["per_ton"] = out["per_kg"] * 1000
    return out


